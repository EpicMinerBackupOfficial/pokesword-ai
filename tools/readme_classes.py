#!/usr/bin/env python3
"""Keep README's "What remains" class table honest.

That table used to be HAND-WRITTEN. `tools/refresh_status_block.py` only
regenerates the status block at the top of the README, so the class table below it
drifted silently -- it described "~125,500 remaining functions" when the figure is
114,209, and counted `branchy` at 22,548 when the conditional population is 85,758.

The failure mode is the same one this project keeps meeting: a number nobody
recomputes is a number nobody notices being wrong. So the table is now DERIVED, by
this tool, and `--write` puts it back into the README.

Classes are derived from the shapes `shape_of` returns for UNMATCHED bodies, plus
whether the body makes a call, which is the distinction the table was trying to
make by hand.

Usage:
    python tools/readme_classes.py            # print the current census
    python tools/readme_classes.py --write    # and rewrite the README table
    python tools/readme_classes.py --check    # exit 1 if the README is stale
"""
import argparse
import collections
import io
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))

import capstone

import auto_match as AM
import match_harness as MH

MODULES = ("rtld", "main", "sdk", "subsdk0", "subsdk1")
CALLS = ("bl", "blr")
COND = ("b.eq", "b.ne", "b.lt", "b.le", "b.gt", "b.ge", "b.hi", "b.hs",
        "b.lo", "b.ls", "b.cc", "b.cs", "b.mi", "b.pl", "b.vs", "b.vc",
        "cbz", "cbnz", "tbz", "tbnz")

BEGIN = "<!-- BEGIN readme_classes -->"
END = "<!-- END readme_classes -->"

NATURE = {
    "branchy-calls": "branches plus calls; genuine decompilation",
    "branchy": "branches, no call",
    "linear-with-calls": "branch-free, but makes calls",
    "branch-free": "branch-free, partially tractable",
    "tailcall": "argument-setup prefix plus `b`; the branch IS the return",
    "undecodable": "did not disassemble",
}
ORDER = ("branchy-calls", "branchy", "linear-with-calls", "branch-free",
         "tailcall", "undecodable")


def census():
    md = capstone.Cs(capstone.CS_ARCH_ARM64, capstone.CS_MODE_ARM)
    cls = collections.Counter()
    shapes = collections.Counter()
    unmatched = matched = 0
    for mod in MODULES:
        try:
            rows = MH.load_functions(mod)
            blob = MH.text_blob(mod)
            rp = os.path.join(ROOT, "data", "matched_%s.json" % mod)
            reg = {(r["addr"], r["size"]) for r in json.load(
                io.open(rp, encoding="utf-8"))["matched"]} \
                if os.path.exists(rp) else set()
        except Exception:
            continue
        for addr, size, name, m in rows:
            if (addr, size) in reg:
                matched += 1
                continue
            unmatched += 1
            ins = list(md.disasm(blob[addr:addr + size], addr))
            if not ins:
                cls["undecodable"] += 1
                continue
            end = MH.effective_end(ins, size)
            mn = [i.mnemonic for i in ins[:end]]
            has_call = any(x in CALLS for x in mn)
            sh = AM.shape_of(ins, end)
            shapes[sh] += 1
            if sh == "tailcall":
                cls["tailcall"] += 1
            elif sh in ("branchy", "guarded") or any(x in COND for x in mn):
                cls["branchy-calls" if has_call else "branchy"] += 1
            elif has_call:
                cls["linear-with-calls"] += 1
            else:
                cls["branch-free"] += 1
    return cls, shapes, matched, unmatched


def table(cls, shapes, unmatched):
    lines = [BEGIN, "",
             "The remaining **%s** functions are dominated by real control flow."
             % f"{unmatched:,}", "",
             "| class | bodies | nature |", "|---|---:|---|"]
    for k in ORDER:
        lines.append("| `%s` | %s | %s |" % (k, f"{cls[k]:,}", NATURE[k]))
    lines += ["", "Largest shapes among the unmatched, by `shape_of`:", "",
              "| shape | bodies |", "|---|---:|"]
    for sh, v in shapes.most_common(8):
        if sh:
            lines.append("| `%s` | %s |" % (sh, f"{v:,}"))
    total = sum(cls[k] for k in ORDER)
    if total != unmatched:
        # A table that does not sum to its own total is worse than no table: it
        # looks authoritative and hides its own gap. Refuse to write it.
        raise SystemExit("class table sums to %d but %d bodies are unmatched; "
                         "a class is missing from ORDER" % (total, unmatched))
    lines += ["",
              "Generated by `tools/readme_classes.py`. The table used to be written",
              "by hand, which is how it came to describe 125,500 remaining functions",
              "when the figure was 114,209.", END]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    cls, shapes, matched, unmatched = census()
    if not args.write and not args.check:
        print("  matched %d   unmatched %d" % (matched, unmatched))
        for k in ORDER:
            print("   %-18s %7d" % (k, cls[k]))
        print("   top shapes: %s" % ", ".join(
            "%s=%d" % (s, v) for s, v in shapes.most_common(6) if s))
        return 0

    body = table(cls, shapes, unmatched)
    p = os.path.join(ROOT, "README.md")
    t = io.open(p, encoding="utf-8").read()
    if BEGIN in t and END in t:
        out = t[:t.index(BEGIN)] + body + t[t.index(END) + len(END):]
    else:
        # First run: replace the hand-written table, from its header to the line
        # before the paragraph that follows it.
        m = re.search(r"^The remaining .*?\n\n(?:\|.*\n)+\n", t, re.M | re.S)
        if not m:
            print("  could not find the hand-written table to replace")
            return 2
        out = t[:m.start()] + body + "\n\n" + t[m.end():]

    if args.check:
        if out.strip() == t.strip():
            print("  README class table is current")
            return 0
        print("  README class table is STALE -- run with --write")
        return 1

    io.open(p, "w", encoding="utf-8", newline="").write(out)
    print("  README class table rewritten from the current registry")
    return 0


if __name__ == "__main__":
    sys.exit(main())